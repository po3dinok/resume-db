for title, city, needed, keywords in requests:
    # Build query: match any keyword in desired_position OR experience_and_education
    conditions = []
    params = [f'%{city}%']
    
    for kw in keywords:
        conditions.append("(desired_position LIKE ? OR experience_and_education LIKE ?)")
        params.extend([f'%{kw}%', f'%{kw}%'])
    
    query = f"SELECT COUNT(*) FROM resumes WHERE city LIKE ? AND ({' OR '.join(conditions)})"
